package suwayomi.tachidesk.manga.impl.fork

import io.github.oshai.kotlinlogging.KotlinLogging
import kotlinx.coroutines.CancellationException
import org.jetbrains.exposed.v1.core.SortOrder
import org.jetbrains.exposed.v1.core.Table
import org.jetbrains.exposed.v1.core.and
import org.jetbrains.exposed.v1.core.eq
import org.jetbrains.exposed.v1.core.greaterEq
import org.jetbrains.exposed.v1.core.less
import org.jetbrains.exposed.v1.jdbc.insert
import org.jetbrains.exposed.v1.jdbc.selectAll
import org.jetbrains.exposed.v1.jdbc.transactions.transaction
import suwayomi.tachidesk.manga.impl.ChapterDownloadHelper
import suwayomi.tachidesk.manga.impl.download.model.DownloadQueueItem
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.atomic.AtomicInteger

/**
 * Fork-only (download speeds): one row per chapter download attempt that finished or failed, so each source's download
 * speed can be followed over time. Design: docs/superpowers/specs/2026-10-25-chapter-download-speeds-design.md in the
 * unraid repo.
 */
object ChapterDownloadStats {
    private val logger = KotlinLogging.logger {}

    /** Created by ForkSchema. */
    const val TABLE = "fork_chapter_download"
    const val SOURCE_STARTED_INDEX = "fork_chapter_download_source_started"

    /** ForkSchema's columns for [TABLE]. No foreign keys: a fork table mustn't hold up an upstream migration. */
    const val COLUMNS =
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source BIGINT NOT NULL, manga INT NOT NULL, " +
            "chapter INT NOT NULL, attempt INT NOT NULL, started_at BIGINT NOT NULL, list_ms INT NOT NULL, " +
            "total_ms INT NOT NULL, pages INT NOT NULL, pages_fetched INT NOT NULL, bytes BIGINT NOT NULL, " +
            "page_retries INT NOT NULL, outcome VARCHAR(300) NOT NULL"

    /** The outcome of an attempt that downloaded the chapter. */
    const val OK = "ok"
    const val MAX_OUTCOME = 300

    /** list_ms of an attempt whose page list never arrived. */
    const val NO_PAGE_LIST = -1

    private object ChapterDownloadTable : Table(TABLE) {
        val id = long("id").autoIncrement()

        // "source" would hide ColumnSet.source
        val sourceId = long("source")
        val manga = integer("manga")
        val chapter = integer("chapter")
        val attempt = integer("attempt")
        val startedAt = long("started_at")
        val listMs = integer("list_ms")
        val totalMs = integer("total_ms")
        val pages = integer("pages")
        val pagesFetched = integer("pages_fetched")
        val bytes = long("bytes")
        val pageRetries = integer("page_retries")
        val outcome = varchar("outcome", MAX_OUTCOME)

        override val primaryKey = PrimaryKey(id)
    }

    data class Attempt(
        val sourceId: Long,
        val mangaId: Int,
        val chapterId: Int,
        /** which try this was, from 1 */
        val attempt: Int,
        /** epoch ms when the downloader started this attempt */
        val startedAt: Long,
        /** time to get the page list, or [NO_PAGE_LIST] */
        val listMs: Int,
        val totalMs: Int,
        val pages: Int,
        /** size of the finished CBZ or chapter folder; 0 for a failure */
        val bytes: Long,
        val pageRetries: Int,
        /** [OK], or the failure's class and the first line of its message */
        val outcome: String,
        /** pages this attempt downloaded; pages left in the cache by an earlier attempt or the reader aren't counted */
        val pagesFetched: Int = pages,
    )

    /** Writes [row]. A failure is logged, never thrown: recording must not break a download. */
    fun record(row: Attempt) {
        try {
            transaction {
                // Exposed retries a failed transaction (3 attempts by default); a missing table won't appear meanwhile
                maxAttempts = 1
                ChapterDownloadTable.insert {
                    it[sourceId] = row.sourceId
                    it[manga] = row.mangaId
                    it[chapter] = row.chapterId
                    it[attempt] = row.attempt
                    it[startedAt] = row.startedAt
                    it[listMs] = row.listMs
                    it[totalMs] = row.totalMs
                    it[pages] = row.pages
                    it[pagesFetched] = row.pagesFetched
                    it[bytes] = row.bytes
                    it[pageRetries] = row.pageRetries
                    it[outcome] = row.outcome.take(MAX_OUTCOME)
                }
            }
        } catch (e: Exception) {
            logger.warn(e) { "couldn't record a download attempt of chapter ${row.chapterId}; the download goes on" }
        }
    }

    /** Attempts started in [since, until), oldest first; only [sourceId]'s when it's given. */
    fun attempts(
        since: Long,
        until: Long,
        sourceId: Long? = null,
    ): List<Attempt> =
        transaction {
            val inWindow = (ChapterDownloadTable.startedAt greaterEq since) and (ChapterDownloadTable.startedAt less until)
            ChapterDownloadTable
                .selectAll()
                .where { if (sourceId == null) inWindow else inWindow and (ChapterDownloadTable.sourceId eq sourceId) }
                .orderBy(ChapterDownloadTable.startedAt to SortOrder.ASC, ChapterDownloadTable.id to SortOrder.ASC)
                .map {
                    Attempt(
                        sourceId = it[ChapterDownloadTable.sourceId],
                        mangaId = it[ChapterDownloadTable.manga],
                        chapterId = it[ChapterDownloadTable.chapter],
                        attempt = it[ChapterDownloadTable.attempt],
                        startedAt = it[ChapterDownloadTable.startedAt],
                        listMs = it[ChapterDownloadTable.listMs],
                        totalMs = it[ChapterDownloadTable.totalMs],
                        pages = it[ChapterDownloadTable.pages],
                        bytes = it[ChapterDownloadTable.bytes],
                        pageRetries = it[ChapterDownloadTable.pageRetries],
                        outcome = it[ChapterDownloadTable.outcome],
                        pagesFetched = it[ChapterDownloadTable.pagesFetched],
                    )
                }
        }

    /** Page retries of each chapter's current attempt; kept out of DownloadQueueItem so the queue's output doesn't change. */
    private val pageRetries = ConcurrentHashMap<Int, AtomicInteger>()

    /** Pages each chapter's current attempt downloaded. */
    private val pagesFetched = ConcurrentHashMap<Int, AtomicInteger>()

    /** The page downloader's hook: one more page downloaded in the current attempt of [chapterId]. */
    fun countPageFetched(chapterId: Int) {
        pagesFetched.computeIfAbsent(chapterId) { AtomicInteger() }.incrementAndGet()
    }

    /** F9's page retry hook: one more retry in the current attempt of [chapterId]. */
    fun countPageRetry(chapterId: Int) {
        pageRetries.computeIfAbsent(chapterId) { AtomicInteger() }.incrementAndGet()
    }

    /** A failed attempt's outcome: the exception's class and the first line of its message, cut to fit. */
    fun outcomeOf(e: Throwable): String {
        // the JVM's names, not Kotlin reflection, which can throw on an extension's obfuscated or converted classes
        val name = runCatching { e.javaClass.simpleName }.getOrNull()?.ifEmpty { null } ?: e.javaClass.name.substringAfterLast('.')
        val line =
            runCatching { e.message }
                .getOrNull()
                ?.lineSequence()
                ?.firstOrNull()
                ?.trim()
                .orEmpty()
        return (if (line.isEmpty()) name else "$name: $line").take(MAX_OUTCOME)
    }

    /**
     * Times one attempt of [download] from when the downloader starts it. [finished] or [failed] writes its row;
     * [abandoned] (stopped, paused, dequeued) writes none.
     */
    class AttemptTimer(
        private val download: DownloadQueueItem,
    ) {
        private val startedAt = System.currentTimeMillis()
        private val startNanos = System.nanoTime()
        private val attempt = download.tries + 1
        private var listMs = NO_PAGE_LIST
        private var pages = 0

        init {
            pageRetries.remove(download.chapterId)
            pagesFetched.remove(download.chapterId)
        }

        fun pageListReady(pageCount: Int) {
            listMs = elapsedMs()
            pages = pageCount.coerceAtLeast(0)
        }

        suspend fun finished() =
            neverThrows {
                val bytes =
                    try {
                        ChapterDownloadHelper.getChapterArchiveSize(download.mangaId, download.chapterId)
                    } catch (e: CancellationException) {
                        throw e
                    } catch (e: Exception) {
                        logger.warn(e) { "couldn't read the size of chapter ${download.chapterId}" }
                        0L
                    }
                record(row(OK, bytes))
            }

        fun failed(e: Throwable) = neverThrows { record(row(outcomeOf(e), 0)) }

        /** Recording must never break a download; only a stop, and the JVM's own errors, get through. */
        private inline fun neverThrows(block: () -> Unit) {
            try {
                block()
            } catch (e: CancellationException) {
                throw e
            } catch (e: VirtualMachineError) {
                throw e
            } catch (e: Throwable) {
                logger.warn(e) { "couldn't record a download attempt of chapter ${download.chapterId}; the download goes on" }
            }
        }

        fun abandoned() {
            pageRetries.remove(download.chapterId)
            pagesFetched.remove(download.chapterId)
        }

        private fun elapsedMs() = ((System.nanoTime() - startNanos) / 1_000_000).toInt()

        private fun row(
            outcome: String,
            bytes: Long,
        ) = Attempt(
            sourceId = download.sourceId,
            mangaId = download.mangaId,
            chapterId = download.chapterId,
            attempt = attempt,
            startedAt = startedAt,
            listMs = listMs,
            totalMs = elapsedMs(),
            pages = pages,
            bytes = bytes,
            pageRetries = pageRetries.remove(download.chapterId)?.get() ?: 0,
            outcome = outcome,
            pagesFetched = pagesFetched.remove(download.chapterId)?.get() ?: 0,
        )
    }
}
